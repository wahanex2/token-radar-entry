// The token radar's model: one sealed snapshot in, one ranked board out.
//
// The board ranks every protocol the radar may rank: each one records no token
// (no market cap, no CoinGecko id, no symbol) and is not a wrapped, staked or
// bridged product of a token that already trades, by the same rule the
// snapshot's watchlist was drawn with. The watchlist is the floor: all 40 of
// its slugs are ranked, and the radar adds every other rankable protocol,
// above and below the floor, so the board is the whole pre-token field the
// snapshot can see, not a capped sample of it.
//
// Implied value follows only from the snapshot's own figures, through one
// function applied to every row alike:
//
//   multiple   = the median market-cap-to-TVL ratio of the snapshot's own
//                live-token protocols (CEX excluded), clamped to [0.05, 1]
//   growth     = clamp(change_7d, -50, 150) per cent (null reads as 0)
//   growthMult = 1 + 0.5 x growth / 100
//   maturity   = 0.55 + 0.45 x (1 - exp(-age_days / 365))  (unknown age: 365)
//   implied    = max(1, round(tvl_usd x multiple x growthMult x maturity))
//
// The multiple is calibrated from the snapshot at run time, never typed in:
// it is what the market already pays per dollar of TVL for protocols whose
// token trades. Growth is bounded so one wild week cannot crown a protocol,
// and maturity saturates: a year running with no token already says most of
// what age can say. No protocol name is ever special-cased.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants: the dashboard states them and the sandbox may change them. */
export interface ModelConstants {
  /** Median live mcap/TVL, clamped into this range; computed from the snapshot. */
  multiple_floor: number;
  multiple_cap: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_scale_days: number;
  unknown_age_days: number;
}

export const MODEL: ModelConstants = {
  multiple_floor: 0.05,
  multiple_cap: 1.0,
  growth_weight: 0.5,
  growth_floor: -50,
  growth_cap: 150,
  maturity_floor: 0.55,
  maturity_range: 0.45,
  maturity_scale_days: 365,
  unknown_age_days: 365,
};

